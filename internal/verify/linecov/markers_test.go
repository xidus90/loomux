func TestScanTakesAReasonOnlyFromCommentText(t *testing.T) {
	missing := func(rel, label string, lines ...int) []Finding {
		var fs []Finding
		for _, l := range lines {
			fs = append(fs, Finding{rel, l, label + " without a reason"})
		}
		return fs
	}
	for name, c := range map[string]struct {
		rel, src string
		want     []Finding
	}{
		"code above":                  {"a.py", "x = 1\ny = 2  # pragma: no cover\n", missing("a.py", "pragma: no cover", 2)},
		"empty comment above":         {"a.py", "#\ny = 2  # pragma: no cover\n", missing("a.py", "pragma: no cover", 2)},
		"text after the closer":       {"a.js", "/* istanbul ignore next */ foo();\n", missing("a.js", "istanbul ignore", 1)},
		"closer, comment above":       {"a.js", "// flag\n/* istanbul ignore next */ foo();\n", nil},
		"code after an attribute":     {"a.cs", "[ExcludeFromCodeCoverage] public void X()\n", missing("a.cs", "ExcludeFromCodeCoverage", 1)},
		"a marker above is no reason": {"a.py", "x = 1  # pragma: no cover -- why\n# pragma: no cover\ny = 2  # pragma: no cover\n", missing("a.py", "pragma: no cover", 2, 3)},
	} {
		s := ScanSource(c.rel, []byte(c.src), natives(t))
		if len(s.Findings) != len(c.want) || (len(c.want) > 0 && !reflect.DeepEqual(s.Findings, c.want)) {
			t.Errorf("%s: %v", name, s.Findings)
		}
	}
}

