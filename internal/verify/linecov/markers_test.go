func natives(t *testing.T) []Marker {
	t.Helper()
	ps, err := LoadProfiles()
	if err != nil {
		t.Fatal(err)
	}
	return Natives(ps, nil)
}

func TestScanFindsOwnMarkersOnTheLineAndAboveIt(t *testing.T) {
	src := "a = 1  # coverage:exempt only on Windows\n" +
		"# coverage:exempt the line below is generated\n" +
		"b = 2\n" +
		"c = 3 // coverage:exempt\n" +
		"d = 4 /* coverage:exempt  */\n" +
		"e = 5 # coverage:exemption is not a marker\n"
	s := ScanSource("a.py", []byte(src), nil)
	want := map[int]exemption{1: {true, true}, 3: {true, true}, 4: {true, false}, 5: {true, false}}
	if !reflect.DeepEqual(s.Lines, want) || s.File || len(s.Findings) != 0 {
		t.Fatalf("%+v", s)
	}
}

func TestScanFindsTheFileMarker(t *testing.T) {
	if s := ScanSource("a.gd", []byte("extends Node\n# coverage:exempt-file only _init, never instrumented\n"), nil); !s.File || !s.FileReason {
		t.Fatalf("%+v", s)
	}
	s := ScanSource("a.gd", []byte("# coverage:exempt-file\n"), nil)
	if !s.File || s.FileReason || !reflect.DeepEqual(s.Findings, []Finding{{"a.gd", 0, "coverage:exempt-file without a reason"}}) {
		t.Fatalf("%+v", s)
	}
}

func TestScanAsksNativeMarkersForAReasonAfterOrAbove(t *testing.T) {
	for _, row := range []struct {
		rel, src string
		lines    []int
		want     []Finding
	}{
		{"a.py", "x = 1  # pragma: no cover\ny = 2  # pragma: no cover -- debug only\n", []int{1, 2}, []Finding{{"a.py", 1, "pragma: no cover without a reason"}}},
		{"a.php", "// the extension is tested upstream\nfunction two() { return 2; } // @codeCoverageIgnore\n", []int{2}, nil},
		{"a.cs", "[ExcludeFromCodeCoverage(Justification = \"generated\")]\n[ExcludeFromCodeCoverage]  // debugging aid\n", []int{1, 2}, nil},
		{"a.c", "/* LCOV_EXCL_START legacy */\nold();\n/* LCOV_EXCL_STOP */\n", []int{1, 2, 3}, nil},
	} {
		s := ScanSource(row.rel, []byte(row.src), natives(t))
		if !reflect.DeepEqual(s.Findings, row.want) {
			t.Errorf("%s: %v", row.rel, s.Findings)
		}
		for _, n := range row.lines {
			if e, ok := s.Lines[n]; !ok || e.own {
				t.Errorf("%s line %d: %+v %v", row.rel, n, e, ok)
			}
		}
	}
	if s := ScanSource("a.js", []byte("/* istanbul ignore file: generated */\n"), natives(t)); !s.NativeFile || s.File {
		t.Fatalf("%+v", s)
	}
}

// A marker counts where it opens a comment, in the languages of the tool
// that brings it; a mention in a string, in prose or in another language's
// file is none.
func TestScanCountsMarkersOnlyWhereTheyOpenAComment(t *testing.T) {
	for _, row := range []struct {
		rel, src string
		line     int
		want     bool
	}{
		{"a.py", "x = 1  # pragma: no cover r\n", 1, true},
		{"a.py", "x  # type: ignore  # pragma: no cover r\n", 1, true},
		{"a.js", "f(/* istanbul ignore next: r */ x)\n", 1, true},
		{"a.php", "/**\n * generated by the builder\n * @codeCoverageIgnore\n */\n", 3, true},
		{"a.php", "// generated by the builder\n/** @codeCoverageIgnore */\n", 2, true},
		{"a.cs", "[ExcludeFromCodeCoverage]\nvoid X() {}\n", 2, true},
		{"a.rs", "#![coverage(off)]\nfn f() {}\n", 2, true},
		{"a.lua", "-- coverage:exempt r\nx()\n", 2, true},
		{"a.go", "x := 1 //coverage:exempt r\n", 1, true},
		{"a.c", "x = \"LCOV_EXCL_LINE\";\n", 1, false},
		{"a.py", "y = \"coverage:exempt r\"\n", 1, false},
		{"a.py", "y = 'coverage:exempt r'\n", 1, false},
		{"a.c", "// mentions LCOV_EXCL_LINE in prose\nx();\n", 1, false},
		{"a.c", "// mentions LCOV_EXCL_LINE in prose\nx();\n", 2, false},
		{"a.py", "x = 1  # LCOV_EXCL_LINE r\n", 1, false},
		{"a.js", "x = 1;  # pragma: no cover r\n", 1, false},
	} {
		s := ScanSource(row.rel, []byte(row.src), natives(t))
		if _, ok := s.Lines[row.line]; ok != row.want {
			t.Errorf("%s %q line %d: %v", row.rel, row.src, row.line, ok)
		}
	}
	if s := ScanSource("a.go", []byte("// see coverage:exempt-file for details\n"), nil); s.File || len(s.Findings) != 0 {
		t.Fatalf("%+v", s)
	}
}

